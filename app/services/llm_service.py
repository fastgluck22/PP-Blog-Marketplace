from ollama import AsyncClient


async def generate_answer(question: str, context: str) -> str:
    client = AsyncClient(host="http://localhost:11434")

    response = await client.chat(
        model="llama3.2:3b",
        messages=[
            {
                "role": "system",
                "content": (
                    "Ты помощник базы знаний.\n\n"
                    "Твоя задача — отвечать на вопросы пользователя "
                    "ТОЛЬКО на основе предоставленного контекста.\n\n"
                    "Правила:\n"
                    "1. Используй только информацию из контекста.\n"
                    "2. Не добавляй факты, характеристики, цифры или рекомендации, "
                    "которых нет в контексте.\n"
                    "3. Не используй свои общие знания.\n"
                    "4. Если контекст не содержит информации, позволяющей непосредственно "
                    "ответить на вопрос, не пытайся вывести ответ самостоятельно. "
                    "Скажи: \"В базе знаний недостаточно информации для точного ответа.\" \n"
                    "5. Отвечай только на заданный вопрос.\n"
                    "6. Не упоминай слова «контекст», «статья», «база знаний» "
                    "или внутреннюю работу системы, если это не требуется для ответа.\n"
                    "7. Отвечай на русском языке.\n"
                    "8. Не придумывай отсутствующие детали.\n"
                    "9. Если в контексте есть несколько вариантов или характеристик, "
                    "перечисляй только те, которые относятся к вопросу.\n"
                    "10. Отвечай кратко и по существу."
                    "11. Не делай выводов или рекомендаций, которых прямо нет в контексте. "
                    "Даже если информация из контекста может косвенно относиться к вопросу, "
                    "не представляй её как готовый ответ, если контекст этого не утверждает.\n"
                    "12. Если вопрос касается конкретной задачи, а контекст не содержит "
                    "информации именно об этой задаче, сообщи, что в базе знаний "
                    "недостаточно информации для точного ответа."
                ),
            },
            {
                "role": "user",
                "content": (
                    f"Контекст:\n{context}\n\n"
                    f"Вопрос пользователя:\n{question}\n\n"
                    "Сформулируй ответ на русском языке, "
                    "используя только информацию из контекста."
                ),
            },
        ],
    )

    return response["message"]["content"]